def main() -> int:
    builder = UnannouncedAbsenceGuideBuilder()
    builder.cover()
    builder.intro()
    builder.prep()
    builder.login_and_accounts()
    builder.where_to_go()
    builder.tips()
    for sc in SCENARIOS:
        builder.scenario(sc)
    builder.quick_path()
    builder.operator_checklist()
    builder.save(OUT_PDF)
    print(f"PDF written: {OUT_PDF}")
    print(f"Size: {OUT_PDF.stat().st_size:,} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
