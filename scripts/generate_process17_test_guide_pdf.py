#!/usr/bin/env python3
"""تولید PDF راهنمای تست فرایند ۱۷ — کنسل جلسات درمان آموزشی توسط دانشجو."""

from __future__ import annotations

from pathlib import Path

import arabic_reshaper
from bidi.algorithm import get_display
from fpdf import FPDF

ROOT = Path(__file__).resolve().parents[1]
FONT_REG = ROOT / "app" / "assets" / "fonts" / "Vazirmatn-Regular.ttf"
FONT_BOLD = ROOT / "app" / "assets" / "fonts" / "Vazirmatn-Bold.ttf"
OUTPUT = ROOT / "docs" / "راهنمای-تست-فرایند-۱۷-کنسل-جلسات-درمان-آموزشی.pdf"


def fa(text: str) -> str:
    """آماده‌سازی متن فارسی برای PDF."""
    reshaped = arabic_reshaper.reshape(text)
    return get_display(reshaped)


class GuidePDF(FPDF):
    def __init__(self):
        super().__init__()
        self.add_font("Vazir", "", str(FONT_REG))
        self.add_font("Vazir", "B", str(FONT_BOLD))
        self.set_auto_page_break(auto=True, margin=18)
        self.set_margins(18, 18, 18)

    def rtl_cell(self, w, h, txt, style="", ln=1, align="R"):
        self.set_font("Vazir", style, 11)
        self.multi_cell(w, h, fa(txt), align=align, new_x="LMARGIN", new_y="NEXT")
        if ln:
            self.ln(1)

    def section_title(self, title: str):
        self.ln(3)
        self.set_font("Vazir", "B", 14)
        self.set_fill_color(239, 246, 255)
        self.multi_cell(0, 10, fa(title), align="R", fill=True, new_x="LMARGIN", new_y="NEXT")
        self.ln(2)

    def sub_title(self, title: str):
        self.set_font("Vazir", "B", 12)
        self.multi_cell(0, 8, fa(title), align="R", new_x="LMARGIN", new_y="NEXT")
        self.ln(1)

    def body(self, text: str, size: int = 11):
        self.set_font("Vazir", "", size)
        self.multi_cell(0, 7, fa(text), align="R", new_x="LMARGIN", new_y="NEXT")
        self.ln(1)

    def bullet_list(self, items: list[str]):
        for item in items:
            self.set_font("Vazir", "", 11)
            self.multi_cell(0, 7, fa(f"• {item}"), align="R", new_x="LMARGIN", new_y="NEXT")
        self.ln(2)

    def checkbox_list(self, items: list[str]):
        for item in items:
            self.set_font("Vazir", "", 11)
            self.multi_cell(0, 7, fa(f"[ ] {item}"), align="R", new_x="LMARGIN", new_y="NEXT")
        self.ln(2)


