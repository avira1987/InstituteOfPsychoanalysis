class EducationalLeaveGuideBuilder(PdfBuilder):
    def cover(self) -> None:
        p = self.pdf
        p.add_page()
        p.set_font("Vazir", "B", _TITLE)
        p.ln(8)
        p.cell(
            0,
            12,
            _fa("راهنمای آزمایش و استفاده"),
            align="C",
            new_x="LMARGIN",
            new_y="NEXT",
        )
        p.set_font("Vazir", "B", 13)
        p.cell(
            0,
            10,
            _fa("فرایند شماره ۱ — مرخصی آموزشی موقت از ثبت‌نام در کلاس‌ها"),
            align="C",
            new_x="LMARGIN",
            new_y="NEXT",
        )
        p.ln(6)
        p.set_font("Vazir", "", _BODY)
        p.multi_cell(
            0,
            6,
            _fa(
                "این کتابچه برای اپراتور، پذیرش، یا ناظر کیفیت نوشته شده است "
                "تا بدون نیاز به دانش فنی، مراحل «درخواست وقفه تحصیلی» را "
                "در سامانه امتحان کند و مطمئن شود همهٔ بخش‌ها درست کار می‌کنند."
            ),
            align="R",
        )
        p.ln(5)
        for label, blank in [
            ("نام آزمایش‌کننده", "________________________"),
            ("تاریخ آزمایش", "________________________"),
            ("آدرس سایت", "________________________"),
        ]:
            p.cell(0, 8, _fa(f"{label}: {blank}"), align="R", new_x="LMARGIN", new_y="NEXT")

