    def login_and_accounts(self) -> None:
        self.pdf.add_page()
        self._section_bar("ورود به سامانه")
        self._numbered_list([
            "مرورگر را باز کنید و به صفحهٔ ورود بروید "
            "(آدرس را از مسئول پروژه بگیرید).",
            "روی «ورود با رمز عبور» بزنید.",
            "سؤال ریاضی را جواب دهید.",
            "نام کاربری و رمز را وارد کنید و «ورود» بزنید.",
            "برای عوض کردن نقش: «خروج» و سپس دوباره ورود با حساب دیگر.",
        ])
        self._section_bar("حساب‌های پیشنهادی برای این آزمایش")
        p = self.pdf
        with p.table(
            col_widths=(62, 58, 28),
            width=p.epw,
            text_align=Align.R,
            line_height=5.5,
            borders_layout=TableBordersLayout.ALL,
            cell_fill_color=_COLOR_STRIPE,
            cell_fill_mode=TableCellFillMode.ROWS,
            padding=1.5,
        ) as table:
            hr = table.row()
            for h in [_fa("نقش"), _fa("نام کاربری"), _fa("رمز")]:
                hr.cell(h, align=Align.C, style=_heading_style())
            for role, user, pw in ACCOUNTS:
                row = table.row()
                row.cell(_fa(role))
                row.cell(user, align=Align.C)
                row.cell(pw, align=Align.C)
        p.ln(4)

